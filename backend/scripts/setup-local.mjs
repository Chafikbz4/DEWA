#!/usr/bin/env node
/* Creates backend/.env.local for a LOCAL development database (the PostGIS
 * container from docker-compose.yml) with freshly generated secrets.
 * Never overwrites an existing .env.local.
 *
 *   docker compose up -d postgres redis
 *   npm run setup:local
 *   npm run db:migrate && npm run db:seed
 *   DEMO_SEED_ALLOW=1 DEMO_PASSWORD=DewaDemo2026x npm run db:seed:demo
 *   npm run start:dev
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const target = '.env.local';
if (existsSync(target)) {
  console.log(`${target} already exists – nothing changed.`);
  process.exit(0);
}
const url = process.env.LOCAL_DATABASE_URL ?? 'postgres://dewa:dewa_local_only@localhost:5432/dewa';
const overrides = {
  NODE_ENV: 'development',
  DATABASE_URL: url,
  DATABASE_URL_UNPOOLED: url,
  REDIS_URL: process.env.LOCAL_REDIS_URL ?? '',
  JWT_ACCESS_SECRET: randomBytes(48).toString('base64'),
  ENCRYPTION_KEY: randomBytes(32).toString('base64'),
  HASH_PEPPER: randomBytes(32).toString('base64'),
  PAYMENT_PROVIDER: 'mock',
  SMS_PROVIDER: 'console',
  EMAIL_PROVIDER: 'console',
  STORAGE_DRIVER: 'local',
  CORS_ORIGINS: 'http://localhost:3000,http://localhost:5173,http://localhost:5174,http://localhost:8081,http://localhost:19006',
  SWAGGER_ENABLED: 'true',
};
const example = readFileSync('.env.example', 'utf8')
  .split('\n')
  .filter((l) => !Object.keys(overrides).some((k) => l.startsWith(`${k}=`)));
writeFileSync(
  target,
  `${example.join('\n').trimEnd()}\n\n# --- generated by npm run setup:local (local development only) ---\n${Object.entries(overrides)
    .map(([k, v]) => `${k}=${v}`)
    .join('\n')}\n`,
);
console.log(`✓ ${target} created for ${url.replace(/:[^:@/]+@/, ':***@')}`);
