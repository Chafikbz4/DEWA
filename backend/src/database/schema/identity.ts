import { sql } from 'drizzle-orm';
import {
  AnyPgColumn,
  boolean,
  check,
  index,
  integer,
  pgTable,
  text,
  uniqueIndex,
  uuid,
  varchar,
} from 'drizzle-orm/pg-core';
import { createdAt, deletedAt, pk, tstz, updatedAt } from './_columns';
import {
  accountStatusEnum,
  consentTypeEnum,
  devicePlatformEnum,
  languageEnum,
  otpPurposeEnum,
  otpTargetTypeEnum,
  roleEnum,
} from './enums';

export const users = pgTable(
  'users',
  {
    id: pk(),
    role: roleEnum('role').notNull(),
    /** Stored lower-cased. */
    email: varchar('email', { length: 254 }),
    /** E.164, e.g. +213550123456 */
    phone: varchar('phone', { length: 16 }),
    passwordHash: text('password_hash').notNull(),
    emailVerifiedAt: tstz('email_verified_at'),
    phoneVerifiedAt: tstz('phone_verified_at'),
    status: accountStatusEnum('status')
      .notNull()
      .default('PENDING_VERIFICATION'),
    preferredLanguage: languageEnum('preferred_language')
      .notNull()
      .default('fr'),
    failedLoginCount: integer('failed_login_count').notNull().default(0),
    lockedUntil: tstz('locked_until'),
    lastLoginAt: tstz('last_login_at'),
    passwordChangedAt: tstz('password_changed_at'),
    mfaEnabled: boolean('mfa_enabled').notNull().default(false),
    /** AES-256-GCM ciphertext of the TOTP secret. */
    mfaSecretEncrypted: text('mfa_secret_encrypted'),
    /** Flag only – no biometric data is ever stored. */
    biometricEnabled: boolean('biometric_enabled').notNull().default(false),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    deletedAt: deletedAt(),
  },
  (t) => [
    check(
      'users_email_or_phone_chk',
      sql`${t.email} IS NOT NULL OR ${t.phone} IS NOT NULL`,
    ),
    check('users_failed_login_count_chk', sql`${t.failedLoginCount} >= 0`),
    uniqueIndex('users_email_uq')
      .on(t.email)
      .where(sql`${t.deletedAt} IS NULL`),
    uniqueIndex('users_phone_uq')
      .on(t.phone)
      .where(sql`${t.deletedAt} IS NULL`),
    index('users_role_idx').on(t.role),
    index('users_status_created_idx').on(t.status, t.createdAt),
  ],
);

export const otpCodes = pgTable(
  'otp_codes',
  {
    id: pk(),
    userId: uuid('user_id').references(() => users.id, {
      onDelete: 'cascade',
    }),
    /** Normalised phone (E.164) or lower-cased email. */
    target: varchar('target', { length: 254 }).notNull(),
    targetType: otpTargetTypeEnum('target_type').notNull(),
    purpose: otpPurposeEnum('purpose').notNull(),
    /** HMAC-SHA256(code, pepper) – the plain code is never stored. */
    codeHash: text('code_hash').notNull(),
    attempts: integer('attempts').notNull().default(0),
    expiresAt: tstz('expires_at').notNull(),
    consumedAt: tstz('consumed_at'),
    createdAt: createdAt(),
  },
  (t) => [
    check('otp_attempts_chk', sql`${t.attempts} >= 0`),
    index('otp_target_purpose_created_idx').on(
      t.target,
      t.purpose,
      t.createdAt,
    ),
    index('otp_user_idx').on(t.userId),
  ],
);

export const devices = pgTable(
  'devices',
  {
    id: pk(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** Stable identifier generated by the client app (not a hardware id). */
    deviceIdentifier: varchar('device_identifier', { length: 128 }).notNull(),
    platform: devicePlatformEnum('platform').notNull(),
    pushToken: text('push_token'),
    appVersion: varchar('app_version', { length: 32 }),
    /** The device unlocks its locally stored refresh token with OS biometrics. */
    biometricEnabled: boolean('biometric_enabled').notNull().default(false),
    lastSeenAt: tstz('last_seen_at'),
    revokedAt: tstz('revoked_at'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    uniqueIndex('devices_user_identifier_uq').on(t.userId, t.deviceIdentifier),
  ],
);

export const sessions = pgTable(
  'sessions',
  {
    id: pk(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** All rotations of one login share a family; reuse revokes the family. */
    familyId: uuid('family_id').notNull(),
    /** HMAC-SHA256 of the opaque refresh token secret. */
    refreshTokenHash: text('refresh_token_hash').notNull(),
    deviceId: uuid('device_id').references(() => devices.id, {
      onDelete: 'set null',
    }),
    ip: varchar('ip', { length: 45 }),
    userAgent: varchar('user_agent', { length: 512 }),
    expiresAt: tstz('expires_at').notNull(),
    revokedAt: tstz('revoked_at'),
    revokeReason: varchar('revoke_reason', { length: 64 }),
    replacedBySessionId: uuid('replaced_by_session_id').references(
      (): AnyPgColumn => sessions.id,
      { onDelete: 'set null' },
    ),
    lastUsedAt: tstz('last_used_at'),
    createdAt: createdAt(),
  },
  (t) => [
    index('sessions_user_idx').on(t.userId),
    index('sessions_family_idx').on(t.familyId),
    index('sessions_device_idx').on(t.deviceId),
  ],
);

export const consentRecords = pgTable(
  'consent_records',
  {
    id: pk(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    consentType: consentTypeEnum('consent_type').notNull(),
    version: varchar('version', { length: 32 }).notNull(),
    grantedAt: tstz('granted_at').notNull().defaultNow(),
    revokedAt: tstz('revoked_at'),
    ip: varchar('ip', { length: 45 }),
    createdAt: createdAt(),
  },
  (t) => [index('consent_user_type_idx').on(t.userId, t.consentType)],
);

/**
 * Names for non-patient accounts (pharmacy staff, delivery company admins,
 * platform admins). Patients use patient_profiles; drivers use drivers.
 */
export const staffProfiles = pgTable('staff_profiles', {
  userId: uuid('user_id')
    .primaryKey()
    .references(() => users.id, { onDelete: 'cascade' }),
  firstName: varchar('first_name', { length: 100 }).notNull(),
  lastName: varchar('last_name', { length: 100 }).notNull(),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});
